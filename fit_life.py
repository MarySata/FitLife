# 1. Знакомство
print('Здравствуйте! Давайте рассчитаем рекомендованную норму воды для вас.')
user_name = input('Как вас зовут? ')
print('Приятно познакомиться,', user_name, end="!")
print(' Мы зададим несколько вопросов. Для ответа используйте цифры.')
print('Если необходимо ввести дробное значение, используйте точку.', end=" ")
print('Например, если ваш рост 165 см, вводите его как 1.65.')
user_age = int(input('Сколько вам полных лет? '))

# 2. Сбор данных
user_weight = float(input('Уточните ваш вес в килограммах: '))
user_height = float(input('Уточните ваш рост в метрах: '))


# 3. Логика расчетов (Функции как "черный ящик": используем арифметику)
def bmi():
    """Расчет ИМТ по формуле вес(кг) / рост(м) в квадрате"""
    user_bmi = user_weight / (user_height ** 2)
    return user_bmi


def water_needed():
    """Объем воды в литрах по формуле вес (кг) * 30 мл / 1000"""
    water_volume = (user_weight * 30) / 1000
    return water_volume


# 4. Вывод красивого результата
